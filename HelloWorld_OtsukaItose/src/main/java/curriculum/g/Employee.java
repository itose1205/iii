package curriculum.g;

public class Employee {
	private String employeeid;
	private String name;
	
    //Getter
	public String getEmployeeId() {
		return employeeid;
	}

	public String getName() {
		return name;
	}
    
	//Setter
	public void setEmployeeId(String id) {
		this.employeeid = id;
	}

	public void setName(String name) {
		this.name = name;
	}
	
	
	
	

}
